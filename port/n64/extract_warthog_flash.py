"""Extract the Warthog's three one-frame CE muzzle-flash variants and marker."""
import contextlib
import hashlib
import json
from pathlib import Path
from PIL import Image
from extract_extended import tag_values
from pack_fp_ammo import globals_for, transform_point
from pack_assets import position

ROOT = Path(__file__).resolve().parents[2]
A = ROOT / 'build/n64/assets'
G = ROOT / 'build/n64/generated'


def extract():
    out = A / 'warthog-muzzle'; out.mkdir(exist_ok=True)
    with (out / 'extract.log').open('w') as log, contextlib.redirect_stdout(log), contextlib.redirect_stderr(log):
        from reclaimer.meta.wrappers.halo1_map import Halo1Map
        from reclaimer.bitmaps.bitmap_decompilation import extract_bitmaps
        h = Halo1Map(); h.load_map(A / 'bloodgulch-decompressed.map')
        entries = h.tag_index.tag_index
        def tag(path, kind):
            i = next(i for i,e in enumerate(entries) if e.path == path and e.class_1.enum_name == kind)
            return h.get_meta(i)
        weapon = tag(r'vehicles\warthog\warthog gun', 'weapon')
        reference = weapon.weap_attrs.triggers.STEPTREE[0].firing_effects.STEPTREE[0].firing_effect
        effect = h.get_meta(reference.id)
        emitter = next(p for e in effect.events.STEPTREE for p in e.particles.STEPTREE
                       if p.particle_type.filepath == r'effects\particles\flash\flash h generic')
        particle = h.get_meta(emitter.particle_type.id)
        bitmap = h.get_meta(particle.bitmap.id)
        assert emitter.flags.stay_attached_to_marker and not emitter.flags.random_initial_angle
        assert particle.flags.animate_once_per_frame
        assert particle.rendering.initial_sequence_count == 3
        assert particle.rendering.looping_sequence_count == particle.rendering.final_sequence_count == 0
        sequences = bitmap.sequences.STEPTREE[particle.rendering.first_sequence_index:][:3]
        assert all(len(s.sprites.STEPTREE) == 1 for s in sequences)
        sprites = [s.sprites.STEPTREE[0] for s in sequences]
        source = dict(effect=tag_values(effect), particle=tag_values(particle),
                      sprites=[tag_values(s) for s in sprites])
        h.meta_to_tag_data(bitmap, 'bitm', entries[particle.bitmap.id & 65535])
        extract_bitmaps(bitmap, 'source', out_dir=out, bitmap_ext='png', halo_map=h)
        images = sorted(out.glob('source*.png'))
    textures, extents = [], []
    for i,s in enumerate(sprites):
        im = Image.open(images[s.bitmap_index]).convert('RGBA')
        bounds = [s.left_side, s.top_side, s.right_side, s.bottom_side]
        im = im.crop(tuple(round(x * (im.width if a%2 == 0 else im.height)) for a,x in enumerate(bounds)))
        im = im.resize((16,16), Image.Resampling.BOX)
        # Same bounded-alpha approximation as the existing weapon effects.
        im.putdata([(round(r*255/peak),round(g*255/peak),round(b*255/peak),round(a*peak/255))
                    if (peak:=max(r,g,b)) else (0,0,0,0) for r,g,b,a in im.getdata()])
        im.save(out / f'flash-{i}.png'); textures.append(im)
        width = s.right_side - s.left_side
        extents.append([-s.registration_point_x/width, (width-s.registration_point_x)/width,
                        s.registration_point_y/width, (s.registration_point_y-s.bottom_side+s.top_side)/width])
    model = json.loads((A / 'extended-raw.json').read_text())['models']['warthog']
    marker_name = effect.locations.STEPTREE[emitter.location].marker_name
    marker = model['markers'][marker_name][0]
    assert marker['node'] == 8 and model['nodes'][8]['name'] == 'frame gun'
    assert marker['q'] == [0,0,0,1]
    offset = list(emitter.relative_offset)
    point = [a+b for a,b in zip(marker['p'],offset)]
    point = position(transform_point(globals_for(model['nodes'], model['nodes'])[marker['node']], point),(0,0,0))
    radius = sum(emitter.radius)/2
    lines = ['/* Owned CE Warthog flash; generated by extract_warthog_flash.py. */', '#include "weapon_effects.h"',
             'const float bg_warthog_flash_marker[3]={' + ','.join(f'{x:.9e}f' for x in point) + '};',
             f'const float bg_warthog_flash_radius={radius:.9e}f;',
             'const float bg_warthog_flash_extents[3][4]={' + ','.join('{'+','.join(f'{x:.9e}f' for x in row)+'}' for row in extents) + '};',
             'const uint32_t bg_warthog_flash_textures[3][256] __attribute__((aligned(8)))={']
    for im in textures:
        lines.append('{'+','.join(f'0x{r:02x}{g:02x}{b:02x}{a:02x}' for r,g,b,a in im.getdata())+'},')
    lines.append('};')
    target = G / 'warthog_flash_data.c'; target.write_text('\n'.join(lines)+'\n')
    inputs = [Path(__file__), A/'bloodgulch-decompressed.map', A/'extended-raw.json',
              ROOT/'port/n64/pack_fp_ammo.py', ROOT/'port/n64/pack_assets.py']
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    report = dict(marker=marker_name, node=marker['node'], point=point, offset=offset, radius=radius,
                  source=source, texture_bytes=3072, sprite_extents=extents,
                  inputs={str(p.relative_to(ROOT)):sha(p) for p in inputs},
                  files={str(target.relative_to(ROOT)):sha(target)})
    (G/'warthog-flash-report.json').write_text(json.dumps(report,indent=2)+'\n')
    print('Packed three Warthog flash variants (3072 bytes), marker',point,'radius',radius)


if __name__ == '__main__': extract()
